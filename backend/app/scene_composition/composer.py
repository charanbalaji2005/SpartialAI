"""Assemble observed + inferred geometry into one complete, closed scene.

Nodes are named so the frontend can match them with metadata:
  bg_<region>          observed background region (wall, floor, sky, ...)
  bg_fill              inferred background hidden behind extracted objects
  bg_shell             inferred back and sides that close the background into a solid
  obj_<nn>_<label>     observed front surface of an object
  obj_<nn>_<label>_back   inferred back + sides (category shape prior, synthesized texture)
  obj_<nn>_<label>_gen    generated by an object model (Stable Fast 3D)
  ground_plane         inferred support plane (hidden by default, open by design)

Every object and the background are closed shells: the observed part plus its
inferred parts are validated for holes, non-manifold edges, winding and normal
orientation, and repaired or regenerated when the check fails.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Callable

import cv2
import numpy as np
import trimesh
from PIL import Image

from ..geometry import completion as comp
from ..geometry import mesh as geo
from ..geometry import repair
from ..object_detection.detector import Detection

THING_BASE = 100

# progress(stage_key, message). Keys: geometry, objects, completion, materials, repair, validation.
Progress = Callable[[str, str], None]


@dataclass
class ComposeResult:
    scene: trimesh.Scene
    nodes: list[dict[str, Any]]
    object_meshes: dict[str, trimesh.Scene]
    stats: dict[str, Any]
    lighting: dict[str, Any]
    ground: dict[str, Any] | None
    target: list[float]
    fill_image: Image.Image
    completeness: dict[str, Any] = field(default_factory=dict)
    groups: dict[str, list[str]] = field(default_factory=dict)   # element -> node names (export checks)
    warnings: list[str] = field(default_factory=list)


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_") or "object"


def despike_depth(depth: np.ndarray, step: int) -> np.ndarray:
    """Remove near/far features only a few pixels wide from the background depth.

    Monocular depth often puts isolated pixels (text, thin graphics, noise) at
    the near or far clamp. Triangulated, each becomes a needle pointing at the
    camera. A grey-scale opening then closing on disparity removes features
    narrower than the kernel and leaves larger structures and edges in place.
    Objects are reconstructed from the original depth, so they are unaffected.
    """
    k = max(3, 2 * step + 1)
    kernel = np.ones((k, k), np.uint8)
    disp = 1.0 / np.maximum(depth.astype(np.float32), 1e-6)
    disp = cv2.morphologyEx(disp, cv2.MORPH_OPEN, kernel)     # drop thin near spikes
    disp = cv2.morphologyEx(disp, cv2.MORPH_CLOSE, kernel)    # drop thin far holes
    return (1.0 / np.maximum(disp, 1e-6)).astype(np.float32)


def _nondegenerate(grid: geo.Grid) -> np.ndarray:
    tri = grid.verts[grid.faces].astype(np.float64)
    area = 0.5 * np.linalg.norm(np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0]), axis=1)
    return area > 1e-12


def compose(rgb: np.ndarray, depth: np.ndarray, cam: geo.Camera, step: int,
            things: list[Detection], stuff: list[Detection],
            object_model: Callable[[Detection, np.ndarray, int], trimesh.Trimesh | None] | None = None,
            progress: Progress | None = None) -> ComposeResult:
    h, w = depth.shape
    say = progress or (lambda _s, _m: None)
    warnings: list[str] = []

    # ------------------------------------------------------------------ geometry
    say("geometry", "Building label map")
    labels = np.zeros((h, w), np.int32)
    stuff_names: dict[int, str] = {0: "background"}
    for i, det in enumerate(sorted(stuff, key=lambda d: d.score)):
        if det.mask is not None:
            labels[det.mask] = i + 1
            stuff_names[i + 1] = slug(det.label)
    for k, det in enumerate(things):
        if det.mask is not None:
            labels[det.mask] = THING_BASE + k

    thing_region = labels >= THING_BASE
    # Infer what is behind the objects (colour + depth inpainting).
    if thing_region.any():
        hole = cv2.dilate(thing_region.astype(np.uint8), cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (15, 15)))
        fill_rgb = cv2.inpaint(rgb, hole, 11, cv2.INPAINT_TELEA)
        # Background depth behind objects should match the background, not shallow foreground steps
        bg_mask = ~thing_region
        bg_depth_val = float(np.median(depth[bg_mask])) if bg_mask.any() else float(depth.max())
        fill_depth = depth.copy()
        fill_depth[hole > 0] = bg_depth_val
        fill_depth = cv2.GaussianBlur(fill_depth, (15, 15), 5.0)
        fill_depth[hole == 0] = depth[hole == 0]
    else:
        hole = np.zeros((h, w), np.uint8)
        fill_rgb, fill_depth = rgb, depth

    photo = Image.fromarray(rgb)
    fill_img = Image.fromarray(fill_rgb)
    mat_photo = geo.material(photo, "photo")
    mat_fill = geo.material(fill_img, "photo_inpainted")

    say("geometry", "Triangulating depth surfaces")
    obj_grid = geo.build_grid(depth, cam, step)
    fill_depth = despike_depth(fill_depth, step)
    bg_grid = geo.build_grid(fill_depth, cam, step)
    # Faces that span a depth discontinuity (face_ok False) are not shown with the photo
    # texture (that would smear it), but they are kept as *inferred* occlusion bridges in
    # the closed shells below, so surfaces have no internal holes.
    obj_valid = _nondegenerate(obj_grid)
    bg_valid, bg_bowtie = repair.manifold_selection(bg_grid.faces, _nondegenerate(bg_grid),
                                                    len(bg_grid.verts))
    obj_grid.face_ok &= obj_valid
    bg_grid.face_ok &= bg_valid
    fy, fx = bg_grid.face_px[:, 1], bg_grid.face_px[:, 0]
    face_label = labels[fy, fx]
    face_hole = hole[fy, fx].astype(bool)

    nodes: list[dict[str, Any]] = []
    meshes_by_node: dict[str, trimesh.Trimesh] = {}

    def add(mesh: trimesh.Trimesh | None, name: str, info: dict[str, Any]) -> None:
        if mesh is None or len(mesh.faces) == 0:
            return
        meshes_by_node[name] = mesh
        bounds = mesh.bounds
        nodes.append({
            "node": name, "faces": int(len(mesh.faces)), "vertices": int(len(mesh.vertices)),
            "bounds": bounds.round(4).tolist(),
            "center": ((bounds[0] + bounds[1]) / 2).round(4).tolist(),
            "default_visible": True, **info,
        })

    # Background regions (observed) and fill (inferred).
    observed_faces = 0
    bg_nodes: list[str] = []
    for sid, name in stuff_names.items():
        sel = bg_grid.face_ok & (face_label == sid) & ~face_hole
        observed_faces += int(sel.sum())
        add(geo.submesh(bg_grid, sel, mat_photo), f"bg_{name}",
            {"label": name, "kind": "region", "status": "observed", "group": "background"})
        bg_nodes.append(f"bg_{name}")
    fill_sel = bg_grid.face_ok & face_hole
    add(geo.submesh(bg_grid, fill_sel, mat_fill), "bg_fill",
        {"label": "hidden background", "kind": "region", "status": "inferred",
         "group": "background", "method": "inpainting (colour + depth)"})
    bg_nodes.append("bg_fill")
    inferred_faces = int(fill_sel.sum())

    # ------------------------------------------------------------------ objects: hidden surfaces
    elements: list[dict[str, Any]] = []
    pending_textures: list[tuple[comp.Completion, np.ndarray, str, int]] = []
    for k, det in enumerate(things):
        if det.mask is None:
            continue
        base = f"obj_{k + 1:02d}_{slug(det.label)}"
        own = labels == THING_BASE + k
        core = cv2.erode(own.astype(np.uint8), np.ones((5, 5), np.uint8)).astype(bool)
        zc = depth[core if core.sum() >= 20 else own]
        lo, hi = float(np.percentile(zc, 1)), float(np.percentile(zc, 98))
        good_obj = own & (depth <= hi) & (depth >= lo)
        if good_obj.any() and (~good_obj & own).any():
            from scipy.ndimage import distance_transform_edt
            indices = distance_transform_edt(~good_obj, return_distances=False, return_indices=True)
            clean_obj_depth = depth.copy()
            clean_obj_depth[own] = depth[indices[0][own], indices[1][own]]
            num = cv2.GaussianBlur(clean_obj_depth * own.astype(float), (5, 5), 1.0)
            den = cv2.GaussianBlur(own.astype(float), (5, 5), 1.0)
            clean_obj_depth[own] = (num / np.maximum(den, 1e-6))[own]
        else:
            clean_obj_depth = depth

        this_grid = geo.build_grid(clean_obj_depth, cam, step)
        vert_in_own = own[this_grid.px[:, 1], this_grid.px[:, 0]]
        face_in_own = vert_in_own[this_grid.faces].all(axis=1) & _nondegenerate(this_grid)

        zf = clean_obj_depth.ravel()[this_grid.faces]
        diffs = zf.max(1) - zf.min(1)
        ratios = zf.max(1) / np.maximum(zf.min(1), 1e-6)
        cut = (ratios > 1.25) & (diffs > max(0.12, 0.08 * float(np.median(zc))))
        sel_all = face_in_own & ~cut
        sel_all, bowtie = repair.manifold_selection(this_grid.faces, sel_all, len(this_grid.verts))
        front = geo.submesh(this_grid, sel_all, mat_photo)
        if front is None or len(front.faces) < 8:
            warnings.append(f"{det.label}: too little geometry, merged into background")
            continue
        occluded = np.zeros(len(front.faces), dtype=bool)
        say("objects", f"Reconstructing hidden surfaces of {det.label}")
        common = {"label": det.label, "kind": "object", "group": base,
                  "confidence": round(det.score, 3), "box": [round(v, 1) for v in det.box],
                  "mask_method": det.mask_method,
                  "mask_score": None if det.mask_score is None else round(det.mask_score, 3),
                  "median_depth": round(float(np.median(depth[det.mask])), 3)}
        repairs = []
        if bowtie:
            repairs.append(f"removed {bowtie} faces at non-manifold (bow-tie) vertices")
        generated = None
        if object_model is not None:
            try:
                generated = object_model(det, front.vertices, k)
            except Exception as exc:  # noqa: BLE001
                warnings.append(f"{det.label}: object model failed ({exc}); used shape-prior completion")
        if generated is not None:
            generated, actions = repair.repair_single(generated)
            repairs += actions
            add(front, base, {**common, "status": "observed", "default_visible": False})
            add(generated, f"{base}_gen", {**common, "status": "generated", "method": "Stable Fast 3D"})
            inferred_faces += len(generated.faces)
            elements.append({"name": base, "label": det.label, "kind": "object", "parts": [generated],
                             "nodes": [base, f"{base}_gen"], "method": "Stable Fast 3D",
                             "repairs": repairs, "prior": None, "profile": None, "thickness": None})
        else:
            c = comp.close_object(front, det.mask, clean_obj_depth, det.label)
            add(front, base, {**common, "status": "observed"})
            add(c.mesh, f"{base}_back", {**common, "status": "inferred", "method": c.method,
                                         "shape_prior": c.prior.name, "profile": c.prior.profile,
                                         "thickness": round(c.thickness, 4)})
            inferred_faces += len(c.mesh.faces)
            pending_textures.append((c, det.mask, f"{base}_back_texture", k + 1))
            elements.append({"name": base, "label": det.label, "kind": "object",
                             "parts": [front, c.mesh], "nodes": [base, f"{base}_back"],
                             "completion": c, "method": c.method, "repairs": repairs,
                             "prior": c.prior.name, "profile": c.prior.profile,
                             "thickness": round(c.thickness, 4), "bridged_faces": 0})
        observed_faces += len(front.faces)

    # ------------------------------------------------------------------ background completion
    say("completion", "Closing the background into a solid (back and sides)")
    bg_surface = geo.submesh(bg_grid, bg_valid, mat_photo)
    if bg_surface is not None:
        bg_occluded = ~bg_grid.face_ok[bg_valid]
        bg_c = comp.close_background(bg_surface, fill_depth, occluded=bg_occluded)
        add(bg_c.mesh, "bg_shell", {"label": "background back and sides", "kind": "region",
                                    "status": "inferred", "group": "background", "method": bg_c.method})
        inferred_faces += len(bg_c.mesh.faces)
        pending_textures.append((bg_c, np.ones((h, w), bool), "background_back", 0))
        present = [n for n in bg_nodes if n in meshes_by_node]
        elements.append({"name": "background", "label": "background", "kind": "background",
                         "parts": [meshes_by_node[n] for n in present] + [bg_c.mesh],
                         "nodes": present + ["bg_shell"], "completion": bg_c, "method": bg_c.method,
                         "repairs": [f"removed {bg_bowtie} faces at non-manifold (bow-tie) vertices"]
                         if bg_bowtie else [], "bridged_faces": int(bg_occluded.sum()),
                         "prior": "background", "profile": "box",
                         "thickness": round(bg_c.thickness, 4)})

    say("completion", "Estimating the support plane")
    ground = None
    lower = bg_grid.px[:, 1] > 0.6 * h
    lower_lbl = labels[bg_grid.px[:, 1], bg_grid.px[:, 0]] < THING_BASE
    pts = bg_grid.verts[lower & lower_lbl]
    if len(pts) > 4000:
        pts = pts[np.random.default_rng(0).choice(len(pts), 4000, replace=False)]
    plane = geo.fit_ground_plane(pts)
    if plane is not None:
        n, d, ratio = plane
        extent = float(np.ptp(bg_grid.verts, axis=0).max())
        center = np.median(bg_grid.verts, axis=0)
        color = np.median(rgb[int(0.85 * h):].reshape(-1, 3), axis=0).astype(int).tolist()
        add(geo.ground_mesh(n, d, center, extent, color), "ground_plane",
            {"label": "ground plane", "kind": "region", "status": "inferred", "group": "background",
             "method": "RANSAC plane fit", "default_visible": False})
        ground = {"normal": n.round(4).tolist(), "offset": round(d, 4), "inlier_ratio": round(ratio, 3)}

    # ------------------------------------------------------------------ textures for unseen surfaces
    for i, (c, mask, name, seed) in enumerate(pending_textures):
        say("materials", f"Synthesizing texture {i + 1}/{len(pending_textures)} for unseen surfaces")
        is_bg = name == "background_back"
        comp.apply_texture(c, fill_rgb if is_bg else rgb, mask, name, seed, patch=24 if is_bg else 16)

    # ------------------------------------------------------------------ repair
    for e in elements:
        say("repair", f"Checking and repairing {e['name']}")
        e["report"] = repair.analyze(e["parts"])
        if e["report"].complete:
            continue
        c = e.get("completion")
        if e["kind"] == "object" and c is not None:
            # The relief closure failed validation: regenerate a guaranteed-closed shell.
            pts_all = np.concatenate([np.asarray(p.vertices) for p in e["parts"]])
            hull = repair.convex_closure(pts_all, cam, c.mesh.visual.material.baseColorTexture,
                                         c.box, f"{e['name']}_hull")
            back_name = f"{e['name']}_back"
            meshes_by_node[back_name] = hull
            for nd in nodes:
                if nd["node"] == back_name:
                    nd.update(faces=int(len(hull.faces)), vertices=int(len(hull.vertices)),
                              bounds=hull.bounds.round(4).tolist(),
                              method="convex closure (regenerated after failed validation)")
            e["parts"] = [hull]
            e["repairs"].append("relief closure failed validation; regenerated as convex closure")
            e["report"] = repair.analyze([hull])
        elif len(e["parts"]) == 1:
            fixed, actions = repair.repair_single(e["parts"][0])
            for nd_name in e["nodes"]:
                if meshes_by_node.get(nd_name) is e["parts"][0]:
                    meshes_by_node[nd_name] = fixed
            e["parts"] = [fixed]
            e["repairs"] += actions
            e["report"] = repair.analyze([fixed])
        if not e["report"].complete:
            warnings.append(f"{e['name']}: geometry still incomplete after repair "
                            f"({'; '.join(e['report'].issues)})")

    # ------------------------------------------------------------------ validation
    say("validation", "Validating scene completeness")
    for e in elements:
        e["bounds"] = np.array([np.min([p.bounds[0] for p in e["parts"]], axis=0),
                                np.max([p.bounds[1] for p in e["parts"]], axis=0)])
        if e.get("completion") is not None and e["completion"].texture_size:
            e["texture_size"] = list(e["completion"].texture_size)
    completeness = repair.scene_completeness(elements, float(depth.max()))
    for nd in nodes:
        el = next((e for e in elements if nd["node"] in e["nodes"]), None)
        if el is not None:
            nd["closed"] = bool(el["report"].complete)
            nd["element"] = el["name"]

    # Assemble the scene now that every mesh is final; normals are computed after repairs.
    scene = trimesh.Scene()
    for nd in nodes:
        mesh = meshes_by_node[nd["node"]]
        _ = mesh.vertex_normals
        scene.add_geometry(mesh, node_name=nd["node"], geom_name=nd["node"])
    object_meshes: dict[str, trimesh.Scene] = {}
    for e in elements:
        if e["kind"] != "object":
            continue
        obj_scene = trimesh.Scene()
        for nd_name in e["nodes"]:
            if nd_name in meshes_by_node:
                obj_scene.add_geometry(meshes_by_node[nd_name], node_name=nd_name, geom_name=nd_name)
        object_meshes[e["name"]] = obj_scene

    lighting = estimate_lighting(rgb)
    target = np.median(obj_grid.verts, axis=0).round(4).tolist()
    stats = {
        "grid_faces": int(len(obj_grid.faces)),
        "discontinuity_cut_fraction": round(1 - float(bg_grid.face_ok.mean()), 4),
        "observed_faces": int(observed_faces),
        "inferred_faces": int(inferred_faces),
        "observed_ratio": round(observed_faces / max(observed_faces + inferred_faces, 1), 4),
        "texture_coverage": round(min(1.0, observed_faces * step * step / 2 / (h * w)), 4),
        "objects": len(object_meshes),
        "closed_elements": sum(1 for e in elements if e["report"].complete),
        "elements": len(elements),
    }
    # Only the parts that make up each closed shell (an SF3D object's hidden observed front is excluded).
    groups = {e["name"]: [n for n in e["nodes"] if n in meshes_by_node
                          and any(meshes_by_node[n] is p for p in e["parts"])] for e in elements}
    return ComposeResult(scene, nodes, object_meshes, stats, lighting, ground, target, fill_img,
                         completeness, groups, warnings)


def estimate_lighting(rgb: np.ndarray) -> dict[str, Any]:
    gray = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY).astype(np.float32)
    thr = np.percentile(gray, 98)
    bright = gray >= thr
    ys, xs = np.nonzero(bright)
    h, w = gray.shape
    key_color = rgb[bright].mean(0) / 255 if bright.any() else np.ones(3)
    # Direction toward the brightest region, as seen from the camera (very approximate).
    dx = (xs.mean() / w - 0.5) * 2 if len(xs) else 0.0
    dy = (0.5 - ys.mean() / h) * 2 if len(ys) else 1.0
    return {
        "ambient_intensity": round(float(gray.mean() / 255), 3),
        "key_color": [round(float(c), 3) for c in key_color],
        "key_direction": [round(float(dx), 3), round(float(max(dy, 0.2)), 3), 0.5],
        "method": "brightest-region heuristic",
    }
